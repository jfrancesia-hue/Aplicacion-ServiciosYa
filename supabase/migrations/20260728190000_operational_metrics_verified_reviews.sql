create or replace function public.capture_provider_first_response()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_requester_id uuid;
  v_first_request_at timestamptz;
  v_response_at timestamptz;
begin
  if new.chat_id is null or new.remitente_id is null then
    return new;
  end if;

  if not exists (
    select 1
    from public.usuarios as usuario
    where usuario.id = new.remitente_id
      and (
        usuario.rol::text = 'worker'
        or exists (
          select 1
          from public.servicios as servicio
          where servicio.user_id = usuario.id
             or servicio.usuario_id = usuario.id
        )
      )
  ) then
    return new;
  end if;

  select
    message.remitente_id,
    coalesce(
      message.created_at,
      message.creado_en,
      message.fecha_creacion,
      now()
    )
  into v_requester_id, v_first_request_at
  from public.mensajes as message
  where message.chat_id = new.chat_id
    and message.remitente_id is not null
    and message.remitente_id <> new.remitente_id
  order by coalesce(
    message.created_at,
    message.creado_en,
    message.fecha_creacion,
    now()
  )
  limit 1;

  if v_requester_id is null or v_first_request_at is null then
    return new;
  end if;

  if not exists (
    select 1
    from auth.users
    where id = v_requester_id
  ) or not exists (
    select 1
    from auth.users
    where id = new.remitente_id
  ) then
    return new;
  end if;

  v_response_at := coalesce(
    new.created_at,
    new.creado_en,
    new.fecha_creacion,
    now()
  );

  if v_response_at < v_first_request_at then
    return new;
  end if;

  insert into public.provider_chat_response_times (
    chat_id,
    provider_id,
    requester_id,
    first_request_at,
    first_response_at,
    response_minutes
  )
  values (
    new.chat_id,
    new.remitente_id,
    v_requester_id,
    v_first_request_at,
    v_response_at,
    extract(epoch from (v_response_at - v_first_request_at)) / 60.0
  )
  on conflict (chat_id, provider_id) do nothing;

  return new;
end;
$$;

drop trigger if exists capture_provider_first_response
  on public.mensajes;
create trigger capture_provider_first_response
after insert on public.mensajes
for each row execute function public.capture_provider_first_response();

-- No se fuerza un backfill sobre chats históricos: algunos registros antiguos
-- pueden tener participantes ya eliminados. La métrica se completa de manera
-- segura a partir de las respuestas nuevas, sin bloquear conversaciones.

create or replace view public.provider_trust_summary as
with provider_ids as (
  select id as provider_id
  from public.usuarios
  where rol::text = 'worker'
),
review_summary as (
  select
    provider_id,
    count(*)::integer as completed_jobs,
    round(avg(rating)::numeric, 2) as average_rating,
    count(*)::integer as review_count
  from public.service_job_reviews
  group by provider_id
),
response_summary as (
  select
    provider_id,
    count(*)::integer as response_sample_size,
    case
      when count(*) >= 3
        then round(avg(response_minutes)::numeric, 0)
      else null
    end as average_response_minutes
  from public.provider_chat_response_times
  where first_response_at >= now() - interval '90 days'
  group by provider_id
)
select
  provider.provider_id,
  coalesce(review.completed_jobs, 0) as completed_jobs,
  review.average_rating,
  coalesce(review.review_count, 0) as review_count,
  response.average_response_minutes,
  coalesce(response.response_sample_size, 0) as response_sample_size
from provider_ids as provider
left join review_summary as review using (provider_id)
left join response_summary as response using (provider_id);

revoke all on public.provider_trust_summary from anon, authenticated;
grant select on public.provider_trust_summary to service_role;
