create or replace function public.is_operational_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.usuarios
    where id = auth.uid()
      and rol::text = 'admin'
  );
$$;

revoke all on function public.is_operational_admin() from public;
grant execute on function public.is_operational_admin() to authenticated;
grant execute on function public.is_operational_admin() to service_role;

