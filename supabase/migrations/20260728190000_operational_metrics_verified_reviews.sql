create or replace function public.submit_service_job_review(
  p_payment_record_id uuid,
  p_rating smallint,
  p_comment text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.service_confirmation_payments%rowtype;
  v_review public.service_job_reviews%rowtype;
  v_comment text := nullif(trim(coalesce(p_comment, '')), '');
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  if p_rating is null or p_rating < 1 or p_rating > 5 then
    raise exception 'INVALID_RATING';
  end if;

  if v_comment is not null and char_length(v_comment) > 800 then
    raise exception 'COMMENT_TOO_LONG';
  end if;

  select *
  into v_payment
  from public.service_confirmation_payments
  where id = p_payment_record_id
  for update;

  if not found then
    raise exception 'PAYMENT_NOT_FOUND';
  end if;

  if v_payment.payer_id <> auth.uid() then
    raise exception 'ONLY_PAYER_CAN_REVIEW';
  end if;

  if v_payment.status <> 'approved' then
    raise exception 'JOB_NOT_CONFIRMED';
  end if;

  if v_payment.job_status in ('disputed', 'cancelled') then
    raise exception 'JOB_NOT_REVIEWABLE';
  end if;

  update public.service_confirmation_payments
  set
    job_status = 'completed',
    completed_at = coalesce(completed_at, now())
  where id = v_payment.id;

  insert into public.service_job_reviews (
    payment_record_id,
    chat_id,
    reviewer_id,
    provider_id,
    rating,
    comment
  )
  values (
    v_payment.id,
    v_payment.chat_id,
    auth.uid(),
    v_payment.provider_id,
    p_rating,
    v_comment
  )
  on conflict (payment_record_id)
  do update set
    rating = excluded.rating,
    comment = excluded.comment,
    updated_at = now()
  returning * into v_review;

  return jsonb_build_object(
    'ok', true,
    'review_id', v_review.id,
    'job_status', 'completed',
    'rating', v_review.rating
  );
end;
$$;

revoke all on function public.submit_service_job_review(uuid, smallint, text)
  from public;
grant execute on function public.submit_service_job_review(uuid, smallint, text)
  to authenticated;
grant execute on function public.submit_service_job_review(uuid, smallint, text)
  to service_role;

create or replace function public.get_chat_job_status(p_chat_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_result jsonb;
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select jsonb_build_object(
    'payment_record_id', payment.id,
    'status', payment.status,
    'job_status', payment.job_status,
    'amount_total', payment.amount_total,
    'currency', payment.currency,
    'provider_id', payment.provider_id,
    'payer_id', payment.payer_id,
    'is_payer', payment.payer_id = auth.uid(),
    'can_review',
      payment.payer_id = auth.uid()
      and payment.status = 'approved'
      and payment.job_status = 'confirmed'
      and review.id is null,
    'completed_at', payment.completed_at,
    'rating', review.rating,
    'reviewed_at', review.created_at
  )
  into v_result
  from public.service_confirmation_payments as payment
  left join public.service_job_reviews as review
    on review.payment_record_id = payment.id
  where payment.chat_id = p_chat_id
    and payment.status = 'approved'
    and auth.uid() in (payment.payer_id, payment.provider_id)
  order by payment.approved_at desc nulls last, payment.created_at desc
  limit 1;

  return coalesce(v_result, '{}'::jsonb);
end;
$$;

revoke all on function public.get_chat_job_status(uuid) from public;
grant execute on function public.get_chat_job_status(uuid) to authenticated;
grant execute on function public.get_chat_job_status(uuid) to service_role;

