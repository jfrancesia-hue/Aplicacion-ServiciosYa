create or replace function public.track_marketplace_event(
  p_event_name text,
  p_context jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id bigint;
  v_context jsonb := coalesce(p_context, '{}'::jsonb);
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  if p_event_name is null
    or p_event_name !~ '^marketplace_[a-z0-9_]{2,80}$'
  then
    raise exception 'INVALID_EVENT_NAME';
  end if;

  if jsonb_typeof(v_context) <> 'object'
    or octet_length(v_context::text) > 4096
  then
    raise exception 'INVALID_EVENT_CONTEXT';
  end if;

  if exists (
    select 1
    from jsonb_object_keys(v_context) as key_name
    where lower(key_name) = any (
      array[
        'email',
        'telefono',
        'phone',
        'celular',
        'dni',
        'direccion',
        'address',
        'mensaje',
        'message',
        'transcript',
        'transcripcion',
        'nombre',
        'name'
      ]
    )
  ) then
    raise exception 'SENSITIVE_EVENT_CONTEXT';
  end if;

  -- Los identificadores internos no son necesarios para medir el embudo.
  v_context := v_context
    - array[
        'chat_id',
        'provider_id',
        'usuario_id',
        'user_id',
        'payment_id',
        'message_id'
      ];

  insert into public.marketplace_events (
    user_id,
    event_name,
    province,
    city,
    category,
    context
  )
  values (
    auth.uid(),
    p_event_name,
    left(nullif(trim(v_context ->> 'provincia'), ''), 120),
    left(nullif(trim(v_context ->> 'ciudad'), ''), 120),
    left(
      nullif(
        trim(coalesce(v_context ->> 'categoria', v_context ->> 'category')),
        ''
      ),
      120
    ),
    v_context
  )
  returning id into v_event_id;

  return v_event_id;
end;
$$;

revoke all on function public.track_marketplace_event(text, jsonb) from public;
grant execute on function public.track_marketplace_event(text, jsonb)
  to authenticated;
grant execute on function public.track_marketplace_event(text, jsonb)
  to service_role;

alter table public.service_confirmation_payments
  add column if not exists job_status text not null default 'pending',
  add column if not exists completed_at timestamptz;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'service_confirmation_payments_job_status_check'
      and conrelid = 'public.service_confirmation_payments'::regclass
  ) then
    alter table public.service_confirmation_payments
      add constraint service_confirmation_payments_job_status_check
      check (
        job_status in (
          'pending',
          'confirmed',
          'completed',
          'disputed',
          'cancelled'
        )
      );
  end if;
end
$$;

update public.service_confirmation_payments
set job_status = 'confirmed'
where status = 'approved'
  and job_status = 'pending';

create index if not exists service_confirmation_payments_job_status_idx
  on public.service_confirmation_payments (job_status, created_at desc);

create table if not exists public.service_job_reviews (
  id uuid primary key default gen_random_uuid(),
  payment_record_id uuid not null unique
    references public.service_confirmation_payments(id) on delete restrict,
  chat_id uuid not null references public.chats(id) on delete restrict,
  reviewer_id uuid not null references auth.users(id) on delete restrict,
  provider_id uuid not null references auth.users(id) on delete restrict,
  rating smallint not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint service_job_reviews_not_self check (reviewer_id <> provider_id),
  constraint service_job_reviews_comment_length check (
    comment is null or char_length(comment) <= 800
  )
);

create index if not exists service_job_reviews_provider_idx
  on public.service_job_reviews (provider_id, created_at desc);

